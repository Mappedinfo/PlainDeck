import { expect, test } from '@playwright/test'
import JSZip from 'jszip'
import { createDeckTemplate, PROJECT_PATHS, type DeckDocument } from 'plaindeck/core'

test.use({ locale: 'zh-CN', viewport: { width: 1440, height: 1000 } })

async function projectZip(document: DeckDocument): Promise<Buffer> {
  const zip = new JSZip()
  zip.file(PROJECT_PATHS.deck, JSON.stringify(document.deck))
  zip.file(document.deck.theme, JSON.stringify(document.theme))
  for (const path of document.deck.slides) zip.file(path, JSON.stringify(document.slides[path]))
  return zip.generateAsync({ type: 'nodebuffer' })
}

